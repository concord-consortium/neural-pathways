import { S3Item } from "../types/s3-data";
import { AttributeDefinition } from "../types/attributes";
import { DatasetConfig, validateAttributeKeys } from "./dataset-config";

/**
 * The label space this dataset's binary outcome lives in, shared by the three
 * declarations that must agree: the ground truth (`target`), what the model said
 * (`prediction`), and the confidence badge in the item panel
 * (`classificationLabels`, below). The classifier predicts the same space the
 * target is drawn from, so one constant is the honest way to say it — written
 * out three times they can drift, and the drift would be visible: the fields
 * view's axis would disagree with the badge sitting above it.
 *
 * These are also the labels carried as `target_label` alongside `target` in the
 * S3 data.
 */
const CLASSIFICATION_LABELS = { 0: "negative", 1: "positive" };

/**
 * Yelp attributes are derived from fields already present in index.json, so
 * enabling attributes for this dataset requires no data regeneration.
 *
 * `review_stars` and `stars` intentionally alias existing search fields of the
 * same name — the values are identical, so writing them to the flattened search
 * object is a no-op. What the attribute layer adds is the definition and the
 * ability to participate in correlation views.
 */
const attributes: AttributeDefinition[] = [
  {
    key: "review_stars",
    label: "Review rating",
    description: "The star rating the author gave on this individual review, from 1 to 5.",
    type: "integer",
    min: 1,
    max: 5,
  },
  {
    key: "stars",
    label: "Business rating",
    description: "The average star rating of the business being reviewed, from 1 to 5. "
      + "This describes the business overall rather than this particular review.",
    type: "float",
    min: 1,
    max: 5,
  },
  {
    key: "target",
    label: "Actual sentiment",
    description: "The true sentiment label for this review: 1 for positive, 0 for negative. "
      + "This is the ground truth the model was trained to predict.",
    type: "binary",
    valueLabels: CLASSIFICATION_LABELS,
  },
  {
    key: "prediction",
    label: "Predicted sentiment",
    description: "The sentiment the model predicted for this review: 1 for positive, 0 for "
      + "negative. Only defined for reviews the model has scored.",
    type: "binary",
    valueLabels: CLASSIFICATION_LABELS,
    excludeFromRegression: true,
  },
  {
    key: "model_correct",
    label: "Model was correct",
    description: "Whether the model's predicted sentiment matched the actual sentiment. "
      + "Only defined for reviews that have both a prediction and a ground-truth label.",
    type: "binary",
    valueLabels: { 0: "no", 1: "yes" },
  },
  {
    key: "is_synthetic",
    label: "Synthetic review",
    description: "Whether this review was generated by GPT-4o rather than written by a "
      + "Yelp user.",
    type: "binary",
    // "Synthetic review" is a yes/no question, matching how the chips render it.
    valueLabels: { 0: "no", 1: "yes" },
  },
];

validateAttributeKeys(attributes);

export const yelpDataset: DatasetConfig = {
  id: "yelp",
  label: "Yelp Reviews",
  baseUrl: "https://models-resources.s3.amazonaws.com/neural-pathways/data/v1/",
  itemNoun: { singular: "review", plural: "reviews" },
  classificationLabels: CLASSIFICATION_LABELS,
  searchPlaceholder: "stars:5 AND pathway_0:>0.8",
  searchFields: [
    { name: "name", description: "Business name" },
    { name: "city", description: "City" },
    { name: "state", description: "State" },
    { name: "categories", description: "Business categories" },
    { name: "reconstruction_r2", description: "Reconstruction R²" },
  ],
  resolveAttributes() {
    return attributes;
  },
  getAttributeValue(item: S3Item, key: string): number | null {
    switch (key) {
      case "review_stars":
        return item.review_stars ?? null;
      case "stars":
        return item.stars ?? null;
      case "target":
        return item.target;
      case "prediction":
        return item.classification ?? null;
      case "model_correct":
        if (item.classification == null || item.target == null) return null;
        return item.classification === item.target ? 1 : 0;
      case "is_synthetic":
        return "synthetic-gpt" in item.sources ? 1 : 0;
      default:
        return null;
    }
  },
};
