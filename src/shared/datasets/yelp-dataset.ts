import { S3Review } from "../types/s3-data";
import { AttributeDefinition } from "../types/attributes";
import { DatasetConfig, validateAttributeKeys } from "./dataset-config";

/**
 * Yelp attributes are derived from fields already present in index.json, so
 * enabling attributes for this dataset requires no data regeneration.
 *
 * `review_stars` and `stars` intentionally alias existing search fields of the
 * same name — the values are identical, so writing them to the flattened search
 * object is a no-op. What the attribute layer adds is the definition and the
 * ability to participate in correlation views.
 */
const attributes: AttributeDefinition[] = [
  {
    key: "review_stars",
    label: "Review rating",
    description: "The star rating the author gave on this individual review, from 1 to 5.",
    type: "integer",
    min: 1,
    max: 5,
  },
  {
    key: "stars",
    label: "Business rating",
    description: "The average star rating of the business being reviewed, from 1 to 5. "
      + "This describes the business overall rather than this particular review.",
    type: "float",
    min: 1,
    max: 5,
  },
  {
    key: "target",
    label: "Actual sentiment",
    description: "The true sentiment label for this review: 1 for positive, 0 for negative. "
      + "This is the ground truth the model was trained to predict.",
    type: "binary",
  },
  {
    key: "model_correct",
    label: "Model was correct",
    description: "Whether the model's predicted sentiment matched the actual sentiment. "
      + "Only defined for reviews that have both a prediction and a ground-truth label.",
    type: "binary",
  },
  {
    key: "is_synthetic",
    label: "Synthetic review",
    description: "Whether this review was generated by GPT-4o rather than written by a "
      + "Yelp user.",
    type: "binary",
  },
];

validateAttributeKeys(attributes);

export const yelpDataset: DatasetConfig = {
  id: "yelp",
  label: "Yelp Reviews",
  attributes,
  getAttributeValue(review: S3Review, key: string): number | null {
    switch (key) {
      case "review_stars":
        return review.review_stars ?? null;
      case "stars":
        return review.stars ?? null;
      case "target":
        return review.target;
      case "model_correct":
        if (review.classification == null || review.target == null) return null;
        return review.classification === review.target ? 1 : 0;
      case "is_synthetic":
        return "synthetic-gpt" in review.sources ? 1 : 0;
      default:
        return null;
    }
  },
};
